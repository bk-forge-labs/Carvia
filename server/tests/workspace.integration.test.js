const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const express = require('express');
const cookieParser = require('cookie-parser');
const jwt = require('jsonwebtoken');
const {randomUUID} = require('node:crypto');
const {once} = require('node:events');
const uri = process.env.VELTRENNE_WORKSPACE_TEST_MONGO_URI;
test('isolated workspace: permissions, persistence, concurrency, workflow and SMTP deduplication', {skip:!uri},async () => {
  assert.match(uri,/^mongodb:\/\/127\.0\.0\.1:\d+\/veltrenne_workspace_test(?:\?|$)/);
  const previous = {...process.env};
  let server,sink;
  try {
    process.env.JWT_SECRET='isolated-workspace-test-secret';
    process.env.NODE_ENV='test';
    await mongoose.connect(uri);
    await mongoose.connection.dropDatabase();
    const router = require('../routes/workspaceRoutes');
    const User = require('../models/User'), Car = require('../models/Car'), Enquiry = require('../models/Enquiry');
    const Appointment=require('../models/Appointment'),Task=require('../models/FollowUpTask'),Message=require('../models/WorkspaceMessage');
    const Profile = require('../models/DealerProfile');
    await Promise.all(Object.values(mongoose.models).map(model=>model.init()));
    const users = {};
    for (const role of ['dealer','other','admin','buyer']) users[role]=await User.create({
      name:'Isolated '+role,email:role+'@example.invalid',password:'isolated test password',role:role==='other'?'dealer':role,
    });
    await Profile.create({user:users.dealer._id,companyName:'QA dealer',phone:'0000',status:'approved'});
    const car=await Car.create({dealer:users.dealer._id,title:'BMW i4',brand:'BMW',model:'i4',price:30000,year:2023,mileage:0});
    const enquiry=await Enquiry.create({car:car._id,buyer:users.buyer._id,dealer:users.dealer._id,vehicleTitle:'BMW i4',dealerName:'QA dealer',message:'Please arrange a test drive for this vehicle.'});
    const app=express();app.use(express.json(),cookieParser());app.use('/api/workspace',router);app.use(require('../middleware/errorMiddleware').errorHandler);
    server=app.listen(0,'127.0.0.1');await once(server,'listening');
    const base='http://127.0.0.1:'+server.address().port+'/api/workspace';
    async function call(role,path,method='GET',body) {
      const response=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(role?{Cookie:'access_token='+jwt.sign({id:String(users[role]._id)},process.env.JWT_SECRET)}:{})},...(body?{body:JSON.stringify(body)}:{})});
      return {status:response.status,body:await response.json()};
    }
    assert.equal((await call(null,'/options')).status,401);
    assert.equal((await call('buyer','/options')).status,403);
    const data={title:'Viewing',type:'test-drive',startLocal:'2027-03-28T09:00',endLocal:'2027-03-28T10:00',timeZone:'Europe/Berlin',enquiry:String(enquiry._id),vehicle:String(car._id),notes:'Private dealer notes must not be included in customer mail.',requestKey:randomUUID()};
    const created=await call('dealer','/appointments','POST',data);assert.equal(created.status,201);
    const appointment=created.body.data, appointmentId=appointment._id;
    assert.equal(appointment.customer,String(users.buyer._id));
    assert.equal((await call('other','/appointments/'+appointmentId)).status,404);
    assert.equal((await call('admin','/appointments/'+appointmentId)).status,404);
    assert.equal((await call('other','/appointments','POST',{...data,requestKey:randomUUID()})).status,404);
    assert.equal((await call('admin','/appointments','POST',{...data,requestKey:randomUUID()})).status,403);
    assert.equal((await call('dealer','/appointments','POST',data)).body.data._id,appointmentId);
    assert.equal((await call('dealer','/appointments','POST',{...data,title:'Changed replay'})).status,409);
    assert.equal((await call('dealer','/appointments','POST',{...data,requestKey:randomUUID(),owner:String(users.admin._id)})).status,400);
    assert.equal((await call('dealer','/appointments','POST',{...data,requestKey:randomUUID(),startLocal:'2027-03-28T02:30'})).status,400);
    const adminOwn=await call('admin','/appointments','POST',{title:'Private admin meeting',type:'meeting',startLocal:'2027-03-28T09:00',endLocal:'2027-03-28T10:00',timeZone:'Europe/Berlin',requestKey:randomUUID()});
    assert.equal(adminOwn.status,201);
    assert.equal((await call('dealer','/appointments/'+adminOwn.body.data._id)).status,404);
    assert.equal((await call('admin','/appointments/'+adminOwn.body.data._id+'/confirmation','POST',{expectedVersion:0})).status,403);
    const overlap=await call('dealer','/appointments','POST',{...data,requestKey:randomUUID()});assert.equal(overlap.status,409);assert.equal(overlap.body.conflicts.length,1);
    assert.equal((await call('dealer','/appointments','POST',{...data,requestKey:randomUUID(),acceptConflicts:true})).status,201);
    const fresh={...data,startLocal:'2027-04-01T09:00',endLocal:'2027-04-01T10:00'};
    const concurrent=await Promise.all([call('dealer','/appointments','POST',{...fresh,requestKey:randomUUID()}),call('dealer','/appointments','POST',{...fresh,requestKey:randomUUID()})]);
    assert.deepEqual(concurrent.map(x=>x.status).sort(),[201,409]);
    const {requestKey,...edit}=data;
    const moved=await call('dealer','/appointments/'+appointmentId,'PUT',{...edit,startLocal:'2027-04-02T10:00',endLocal:'2027-04-02T11:00',status:'scheduled',expectedVersion:0});
    assert.equal(moved.status,200);assert.equal(moved.body.data.__v,1);
    assert.equal((await call('dealer','/appointments/'+appointmentId,'PUT',{...edit,status:'cancelled',expectedVersion:0})).status,409);
    assert.equal((await call('other','/appointments/'+appointmentId,'PUT',{...edit,status:'cancelled',expectedVersion:1})).status,404);
    const taskData={title:'Call buyer',dueLocal:'2027-03-27T15:00',timeZone:'Europe/Berlin',enquiry:String(enquiry._id),appointment:appointmentId,requestKey:randomUUID()};
    const task=await call('dealer','/tasks','POST',taskData);assert.equal(task.status,201);
    assert.equal((await call('other','/tasks','POST',{...taskData,requestKey:randomUUID()})).status,404);
    const {requestKey:taskKey,...taskEdit}=taskData;
    assert.equal((await call('dealer','/tasks/'+task.body.data._id,'PUT',{...taskEdit,status:'done',expectedVersion:0})).status,200);
    assert.equal((await call('dealer','/tasks/'+task.body.data._id,'PUT',{...taskEdit,status:'open',expectedVersion:0})).status,409);
    assert.equal((await call('admin','/tasks')).body.total,0);
    const followup=await call('dealer','/tasks','POST',{title:'Schedule viewing',dueLocal:'2027-04-01T12:00',timeZone:'Europe/Berlin',enquiry:String(enquiry._id),requestKey:randomUUID()});
    const sourcePayload={...data,startLocal:'2027-04-10T09:00',endLocal:'2027-04-10T10:00',task:followup.body.data._id,requestKey:randomUUID()};
    const source=await call('dealer','/appointments','POST',sourcePayload);assert.equal(source.status,201);
    assert.equal(String((await Task.findById(followup.body.data._id)).appointment),source.body.data._id);
    assert.equal((await call('dealer','/appointments','POST',sourcePayload)).body.data._id,source.body.data._id);
    assert.equal((await call('dealer','/appointments','POST',{...sourcePayload,requestKey:randomUUID(),startLocal:'2027-04-11T09:00',endLocal:'2027-04-11T10:00'})).status,409);
    assert.equal((await call('other','/tasks/'+followup.body.data._id,'PUT',{title:'Hijack',dueLocal:'2027-04-01T12:00',timeZone:'Europe/Berlin',expectedVersion:0})).status,404);
    const messages=[],mode={reject:false,uncertain:false};
    sink=require('../scripts/workspace-mail-sink').createSink({messages,mode});sink.listen(0,'127.0.0.1');await once(sink,'listening');
    Object.assign(process.env,{WORKSPACE_MAIL_SINK:'true',SMTP_HOST:'127.0.0.1',SMTP_PORT:String(sink.address().port),MAIL_FROM:'qa@veltrenne.invalid'});
    const send=()=>call('dealer','/appointments/'+appointmentId+'/confirmation','POST',{expectedVersion:1});
    await Promise.all([send(),send()]);
    assert.equal(messages.length,1);
    const saved=await Message.findOne({appointment:appointmentId});assert.equal(saved.state,'provider-accepted');assert.equal(saved.attempts,1);assert.match(saved.messageId,/^<workspace-/);assert(!saved.text.includes('Private dealer notes'));
    await send();assert.equal(messages.length,1);
    assert.equal((await call('admin','/messages')).body.total,0);
    assert.equal((await call('other','/appointments/'+appointmentId+'/confirmation','POST',{expectedVersion:1})).status,404);
    // Definitive SMTP rejection can be retried once with a versioned attempt token.
    mode.reject=true;
    const second=concurrent.find(r=>r.status===201).body.data;
    await Appointment.updateOne({_id:second._id},{$set:{enquiry:enquiry._id,customer:users.buyer._id}});
    const failed=await call('dealer','/appointments/'+second._id+'/confirmation','POST',{expectedVersion:0});
    assert.equal(failed.body.data.state,'failed');assert.equal(messages.length,1);
    mode.reject=false;
    const retry=()=>call('dealer','/appointments/'+second._id+'/confirmation','POST',{expectedVersion:0,retryFailed:true,expectedAttempts:1});
    await Promise.all([retry(),retry()]);assert.equal(messages.length,2);
    assert.equal((await Message.findOne({appointment:second._id})).attempts,2);
    // A dropped acknowledgement is uncertain, never automatically resent.
    const third=await call('dealer','/appointments','POST',{...data,startLocal:'2027-04-05T10:00',endLocal:'2027-04-05T11:00',requestKey:randomUUID()});
    mode.uncertain=true;
    const uncertain=()=>call('dealer','/appointments/'+third.body.data._id+'/confirmation','POST',{expectedVersion:0});
    assert.equal((await uncertain()).body.data.state,'unknown');
    const count=messages.length;await uncertain();assert.equal(messages.length,count);
    const cancelled=await call('dealer','/appointments/'+appointmentId,'PUT',{...edit,status:'cancelled',expectedVersion:1});
    assert.equal(cancelled.status,200);
    assert.equal((await call('dealer','/appointments/'+appointmentId,'PUT',{...edit,status:'scheduled',expectedVersion:2})).status,400);
    const completed=await call('dealer','/appointments/'+third.body.data._id,'PUT',{...edit,startLocal:'2027-04-05T10:00',endLocal:'2027-04-05T11:00',status:'completed',outcome:'Buyer viewed the vehicle and requested a quote.',expectedVersion:0});
    assert.equal(completed.status,200);
    await mongoose.disconnect();await mongoose.connect(uri);
    assert.equal((await Appointment.findById(appointmentId)).status,'cancelled');
    assert.equal((await Task.findById(task.body.data._id)).status,'done');
    assert.equal((await Message.findOne({appointment:appointmentId})).state,'provider-accepted');
    console.log('Verified workspace role boundaries, conflict serialization, stale edits, task persistence, cancellation/outcome and real local SMTP acceptance/failure/deduplication.');
  } finally {
    if(server) await new Promise(resolve=>server.close(resolve));
    if(sink) await new Promise(resolve=>sink.close(resolve));
    if(mongoose.connection.readyState===1) await mongoose.connection.dropDatabase();
    await mongoose.disconnect();
    for(const key of Object.keys(process.env)) if(!(key in previous)) delete process.env[key];
    Object.assign(process.env,previous);
  }
});
