// Opt-in live API verification. Creates disposable accounts and enquiries, then removes only those IDs.
if(!process.argv.includes('--run'))throw new Error('Use --run to create and clean up isolated verification records.');
require('dotenv').config({quiet:true});
const mongoose=require('mongoose');
const assert=require('node:assert/strict');
const jwt=require('jsonwebtoken');
const crypto=require('node:crypto');
const User=require('../models/User');
const Car=require('../models/Car');
const DealerProfile=require('../models/DealerProfile');
const Enquiry=require('../models/Enquiry');
const express=require('express');
const cookieParser=require('cookie-parser');
const {errorHandler}=require('../middleware/errorMiddleware');
const ids=[];let server;
(async()=>{try{
 await mongoose.connect(process.env.MONGO_URI);
 await Enquiry.init();
 const profiles=await DealerProfile.find({status:'approved'}).select('user').lean();
 const car=await Car.findOne({dealer:{$in:profiles.map(p=>p.user)},isPublished:true,isDemo:{$ne:true},publicationHold:{$in:['',null]}}).lean();
 assert.ok(car,'An approved published listing is required.');
 for(const role of ['buyer','buyer','dealer']){const u=await User.create({name:'Enquiry verification',email:`enquiry-${crypto.randomUUID()}@example.com`,password:crypto.randomBytes(32).toString('hex'),role});ids.push(u._id);}
 const app=express();app.use(express.json());app.use(cookieParser());app.use('/api/enquiries',require('../routes/enquiryRoutes'));app.use(errorHandler);
 server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
 const base=`http://127.0.0.1:${server.address().port}/api/enquiries`;
 const call=async(id,path='',method='GET',body)=>{const response=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(id?{Cookie:`access_token=${jwt.sign({id:String(id)},process.env.JWT_SECRET,{expiresIn:'5m'})}`}:{})},body:body?JSON.stringify(body):undefined});return {status:response.status,body:await response.json()};};
 assert.equal((await call(null)).status,401);
 assert.equal((await call(null,'/summary')).status,401);
 assert.equal((await call(ids[0],'/summary')).status,403);
 assert.equal((await call(ids[2],'/summary')).body.newCount,0);
 assert.equal((await call(ids[2],'','POST',{carId:String(car._id),message:'This is a disposable verification enquiry.'})).status,403);
 assert.equal((await call(ids[0],'','POST',{carId:'bad',message:'This is a disposable verification enquiry.'})).status,400);
 assert.equal((await call(ids[0],'','POST',{carId:String(new mongoose.Types.ObjectId()),message:'This is a disposable verification enquiry.'})).status,404);
 const sample=await Car.findOne({isDemo:true,isPublished:true}).select('_id').lean();
 if(sample)assert.equal((await call(ids[0],'','POST',{carId:String(sample._id),message:'This is a disposable verification enquiry.'})).status,404);
 const payload={carId:String(car._id),message:'Disposable workflow verification. No reply or action required.',dealer:String(ids[2]),buyer:String(ids[1])};
 const results=await Promise.all(Array.from({length:4},()=>call(ids[0],'','POST',payload)));
 assert.ok(results.every(r=>[200,201].includes(r.status)));
 assert.equal(new Set(results.map(r=>r.body.id)).size,1);
 const eid=results[0].body.id;
 const saved=await Enquiry.findById(eid).lean();assert.equal(String(saved.dealer),String(car.dealer));assert.equal(String(saved.buyer),String(ids[0]));
 assert.equal(await Enquiry.countDocuments({buyer:ids[0],car:car._id}),1);
 assert.equal((await call(ids[1])).body.total,0);
 assert.equal((await call(ids[2])).body.total,0);
 assert.equal((await call(ids[2],'/summary')).body.newCount,0);
 const summary=await call(car.dealer,'/summary');
 assert.equal(summary.status,200);assert.ok(summary.body.newCount>=1);
 const buyerList=await call(ids[0]);assert.equal(buyerList.body.total,1);assert.equal(buyerList.body.data[0].buyerEmail,undefined);
 assert.equal((await call(ids[0],`/${eid}`,'PATCH',{status:'closed',previousStatus:'new'})).status,403);
 assert.equal((await call(ids[2],`/${eid}`,'PATCH',{status:'closed',previousStatus:'new'})).status,404);
 const dealerList=await call(car.dealer);
 const dealerItem=dealerList.body.data.find(e=>e.id===eid);assert.equal(dealerItem.buyerName,'Enquiry verification');assert.ok(dealerList.body.data.some(e=>e.id===eid&&e.buyerEmail));
 assert.equal((await call(car.dealer,`/${eid}`,'PATCH',{status:'contacted',previousStatus:'new'})).status,200);
 assert.equal((await call(car.dealer,`/${eid}`,'PATCH',{status:'closed',previousStatus:'new'})).status,409);
 assert.equal((await call(ids[0])).body.data[0].status,'contacted');
 assert.equal((await call(car.dealer,'/summary')).body.newCount,summary.body.newCount-1);
 assert.equal((await call(car.dealer,`/${eid}`,'PATCH',{status:'closed',previousStatus:'contacted'})).status,200);
 assert.equal((await call(car.dealer,'/summary')).body.newCount,summary.body.newCount-1);
 assert.equal((await call(car.dealer,`/${eid}`,'PATCH',{status:'new',previousStatus:'closed'})).status,200);
 assert.equal((await call(car.dealer,'/summary')).body.newCount,summary.body.newCount);
 assert.equal((await call(car.dealer,`/${eid}`,'PATCH',{status:'closed',previousStatus:'new'})).status,200);
 assert.equal((await call(car.dealer,'/summary')).body.newCount,summary.body.newCount-1);
 assert.equal((await call(car.dealer,`/${eid}`,'PATCH',{status:'contacted',previousStatus:'closed'})).status,200);
 await mongoose.disconnect();await mongoose.connect(process.env.MONGO_URI);
 assert.equal((await Enquiry.findById(eid).lean()).status,'contacted');
 console.log('PASS: authenticated HTTP flow, concurrent duplicate prevention, ownership, privacy, dealer status, stale conflicts, persistence after reconnect.');
 }finally{if(mongoose.connection.readyState!==1)await mongoose.connect(process.env.MONGO_URI);if(ids.length){await Enquiry.deleteMany({buyer:{$in:ids}});await User.deleteMany({_id:{$in:ids}});assert.equal(await Enquiry.countDocuments({buyer:{$in:ids}}),0);assert.equal(await User.countDocuments({_id:{$in:ids}}),0);console.log('Verified cleanup of temporary accounts and enquiries.');}if(server)server.close();await mongoose.disconnect();}
})().catch(e=>{console.error(e.name,e.message);process.exitCode=1;});
